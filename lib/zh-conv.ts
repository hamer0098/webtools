/**
 * 简体→繁体字符映射。只覆盖 lib/faker-cn-data.ts 里实际可能出现的字
 * （城市、省份、街道前缀/后缀、"号"）+ 一点冗余。
 * 没列入的字（如"福州市"的"州"在繁体也写"州"）会原样输出。
 */
const SIMP_TO_TRAD: Record<string, string> = {
  // 省份 / 自治区 / 直辖市
  广: '廣', 东: '東', 苏: '蘇', 龙: '龍', 内: '內', 区: '區',
  壮: '壯', 维: '維', 尔: '爾', 庆: '慶', 辽: '遼', 宁: '寧',
  陕: '陝', 云: '雲', 贵: '貴', 肃: '肅',
  // 城市
  头: '頭', 阳: '陽', 温: '溫', 绍: '紹', 兴: '興', 华: '華',
  无: '無', 锡: '錫', 济: '濟', 岛: '島', 烟: '煙', 潍: '濰',
  绵: '綿', 宾: '賓', 汉: '漢', 郑: '鄭', 庄: '莊', 沈: '瀋',
  连: '連', 芜: '蕪', 兰: '蘭', 亚: '亞', 乌: '烏', 鲁: '魯',
  齐: '齊', 萨: '薩', 银: '銀', 厦: '廈', 门: '門',
  // 街道前缀 / 通用
  国: '國', 体: '體', 长: '長', 黄: '黃', 风: '風', 强: '強',
  团: '團', 结: '結', 谊: '誼', 复: '復', 环: '環', 业: '業',
  机: '機', 场: '場', 车: '車', 学: '學', 园: '園', 锦: '錦',
  绣: '繡', 滨: '濱',
  // 数字单位 / 其他
  号: '號',
};

/** 简体字符串 → 繁体字符串（只逐字替换，不处理词级别歧义） */
export function toTraditional(s: string): string {
  let out = '';
  for (const c of s) {
    out += SIMP_TO_TRAD[c] || c;
  }
  return out;
}
